def create_pywake_site(
    ambient_wind_speed: float,
    ambient_ti: float,
    hub_height: float,
    shear_alpha: float,
) -> UniformSite:
    """Create the PyWake site used by the original workflow, including power-law shear."""

    return UniformSite(
        p_wd=[1.0],
        ti=ambient_ti,
        ws=[ambient_wind_speed],
        shear=PowerShear(h_ref=hub_height, alpha=shear_alpha),
    )


