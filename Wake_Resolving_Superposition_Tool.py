def main() -> None:
    """Run the PyWake-to-TurbSim superposition workflow."""

    config = WorkflowConfig()

    D = config.rotor_diameter

    x, y = build_rotated_grid_layout(
        n_rows=config.n_rows,
        n_cols=config.n_cols,
        spacing_x_m=config.streamwise_spacing_D * D,
        spacing_y_m=config.crossflow_spacing_D * D,
        rotation_deg=config.farm_rotation_deg,
    )

    if config.plot_layout:
        plot_farm_layout(
            x,
            y,
            title=(
                f"{config.n_rows} x {config.n_cols} wind farm, "
                f"{config.streamwise_spacing_D:g}D spacing, "
                f"hub height {config.hub_height:g} m"
            ),
        )

    turbine_index = config.turbine_number - 1
    if turbine_index < 0 or turbine_index >= len(x):
        raise IndexError(
            f"turbine_number={config.turbine_number} is outside the farm layout "
            f"range 1-{len(x)}."
        )

    x_centre = x[turbine_index]
    y_centre = y[turbine_index]
    x_probe = x_centre - config.upstream_sampling_distance_D * D

    print(f"Selected turbine: T{config.turbine_number}")
    print(f"Rotor diameter = {config.rotor_diameter:g} m")
    print(f"Hub height     = {config.hub_height:g} m")
    print(f"Sampling plane: {config.upstream_sampling_distance_D:g}D upstream")
    print(f"x_probe = {x_probe:.3f} m")

    # Wake-model construction still uses setup_wind_farm_model from custom_functions.py.
    # The turbine/site are defined here so the PyWake setup matches the original
    # 15 MW / 240 m / 150 m workflow and includes power-law shear.
    wind_turbines = create_iea_15mw_wind_turbines()
    site = create_pywake_site(
        ambient_wind_speed=config.ambient_wind_speed,
        ambient_ti=config.ambient_ti,
        hub_height=config.hub_height,
        shear_alpha=config.shear_alpha,
    )

    simulation_outputs = run_pywake_models(
        model_names=config.models,
        site=site,
        wind_turbines=wind_turbines,
        x=x,
        y=y,
        wind_direction_deg=config.wind_direction_deg,
        wind_speed=config.ambient_wind_speed,
    )

    for model_name, sim_res in simulation_outputs.items():
        if config.plot_full_pywake_plane:
            plot_full_pywake_yz_plane(
                sim_res=sim_res,
                x_probe=x_probe,
                y_centre=y_centre,
                x_layout=x,
                y_layout=y,
                target_index=turbine_index,
                rotor_diameter=config.rotor_diameter,
                hub_height=config.hub_height,
                model_name=model_name,
                turbine_number=config.turbine_number,
            )

        write_pywake_superposed_bts(
            config=config,
            sim_res=sim_res,
            model_name=model_name,
            x_probe=x_probe,
            y_centre=y_centre,
        )


if __name__ == "__main__":
    main()


