def build_rotated_grid_layout(
    n_rows: int,
    n_cols: int,
    spacing_x_m: float,
    spacing_y_m: float,
    rotation_deg: float,
) -> Tuple[np.ndarray, np.ndarray]:
    """
    Build a rectangular wind farm layout and rotate it about the origin.

    Turbine numbering follows row-major ordering:
    T1, T2, ..., Tn.
    """

    x, y = [], []

    for row in range(n_rows):
        for col in range(n_cols):
            x.append(row * spacing_x_m)
            y.append(col * spacing_y_m)

    x = np.asarray(x, dtype=float)
    y = np.asarray(y, dtype=float)

    theta = np.deg2rad(rotation_deg)
    x_rot = x * np.cos(theta) - y * np.sin(theta)
    y_rot = x * np.sin(theta) + y * np.cos(theta)

    return x_rot, y_rot


def plot_farm_layout(x: np.ndarray, y: np.ndarray, title: str = "Wind farm layout") -> None:
    """Plot turbine locations as a quick layout check."""

    fig, ax = plt.subplots(figsize=(8, 8))
    ax.scatter(x, y, s=20)

    for i, (xi, yi) in enumerate(zip(x, y), start=1):
        ax.text(xi + 20, yi + 20, f"T{i}", fontsize=6)

    ax.set_xlabel("x [m]")
    ax.set_ylabel("y [m]")
    ax.set_title(title)
    ax.axis("equal")
    ax.grid(True)
    fig.tight_layout()
    plt.show()


