def run_pywake_models(
    model_names: Iterable[str],
    site,
    wind_turbines,
    x: np.ndarray,
    y: np.ndarray,
    wind_direction_deg: float,
    wind_speed: float,
) -> Dict[str, object]:
    """Run each requested PyWake model using the original custom setup function."""

    outputs: Dict[str, object] = {}

    for model_name in model_names:
        print(f"Running PyWake model: {model_name}")

        wind_farm_model = setup_wind_farm_model(
            site=site,
            wind_turbines=wind_turbines,
            model=model_name,
        )

        outputs[model_name] = wind_farm_model(
            x=x,
            y=y,
            wd=np.asarray([wind_direction_deg]),
            ws=np.asarray([wind_speed]),
        )

    return outputs


def extract_pywake_yz_fields(
    sim_res,
    x_probe: float,
    y_abs: np.ndarray,
    z_abs: np.ndarray,
) -> Tuple[np.ndarray, np.ndarray]:
    """
    Sample PyWake mean velocity and turbulence intensity on a Y-Z plane.

    Returns
    -------
    U_target, TI_target:
        Arrays in TurbSim grid order with shape (ny, nz).
    """

    flow = sim_res.flow_box(
        x=np.asarray([x_probe]),
        y=y_abs,
        h=z_abs,
    )

    U_target = np.asarray(flow.WS_eff.squeeze().values)
    TI_target = np.asarray(flow.TI_eff.squeeze().values)

    # PyWake versions can return either (ny, nz) or (nz, ny).
    if U_target.shape == (len(z_abs), len(y_abs)):
        U_target = U_target.T
        TI_target = TI_target.T

    expected_shape = (len(y_abs), len(z_abs))
    if U_target.shape != expected_shape:
        raise ValueError(
            f"Unexpected PyWake field shape. Expected {expected_shape}, "
            f"got {U_target.shape}."
        )

    return U_target, TI_target

def plot_pywake_sampled_plane(
    sim_res,
    x_probe: float,
    y_centre: float,
    y_ts: np.ndarray,
    z_ts: np.ndarray,
    hub_height: float,
    rotor_diameter: float,
    title: str = "PyWake sampled rotor plane",
) -> None:
    """
    Plot the PyWake velocity field sampled on the TurbSim rotor grid.

    This is the exact rotor-specific target field that is superposed onto the
    baseline TurbSim .bts file.
    """

    y_abs = y_centre + y_ts

    U_target, TI_target = extract_pywake_yz_fields(
        sim_res=sim_res,
        x_probe=x_probe,
        y_abs=y_abs,
        z_abs=z_ts,
    )

    Y, Z = np.meshgrid(y_ts / rotor_diameter, z_ts / rotor_diameter, indexing="ij")

    fig, ax = plt.subplots(figsize=(7, 5), constrained_layout=True)

    c0 = ax.contourf(Y, Z, U_target, levels=40, cmap="viridis")

    ax.axvline(0.0, color="white", linestyle="--", lw=0.7, alpha=0.8)
    ax.axhline(hub_height / rotor_diameter, color="white", linestyle="--", lw=0.7, alpha=0.8)

    rotor_circle = plt.Circle(
        (0.0, hub_height / rotor_diameter),
        0.5,
        fill=False,
        edgecolor="white",
        linewidth=1.6,
    )
    ax.add_patch(rotor_circle)

    ax.set_xlabel(r"$y/D$")
    ax.set_ylabel(r"$z/D$")
    ax.set_title(title)
    ax.set_aspect("equal", adjustable="box")
    ax.invert_xaxis()

    cbar = fig.colorbar(c0, ax=ax, shrink=0.9, pad=0.025)
    cbar.set_label(r"$\overline{U}$ [m s$^{-1}$]")

    plt.show()

    print(f"Rotor-sampled U_target min/max:  {np.nanmin(U_target):.3f}, {np.nanmax(U_target):.3f}")
    print(f"Rotor-sampled TI_target min/max: {np.nanmin(TI_target):.4f}, {np.nanmax(TI_target):.4f}")


def find_upstream_turbines_for_yz_plane(
    x: np.ndarray,
    y: np.ndarray,
    target_index: int,
    rotor_diameter: float,
    y_extent_D: float = 1.5,
    max_turbines: int = 2,
) -> np.ndarray:
    """
    Identify upstream turbine projections that fall within the plotted Y-Z plane.

    This follows the original plotting logic: for WD=270 deg, the flow is treated
    as travelling in the +x direction, so upstream turbines have dx < 0 relative
    to the selected turbine.
    """

    x_centre = x[target_index]
    y_centre = y[target_index]

    dx_D = (x - x_centre) / rotor_diameter
    dy_D = (y - y_centre) / rotor_diameter

    mask = (dx_D < 0.0) & (np.abs(dy_D) <= y_extent_D)
    candidate_indices = np.where(mask)[0]

    if candidate_indices.size == 0:
        return candidate_indices

    candidate_indices = candidate_indices[np.argsort(np.abs(dx_D[candidate_indices]))]
    return candidate_indices[:max_turbines]


def plot_full_pywake_yz_plane(
    sim_res,
    x_probe: float,
    y_centre: float,
    x_layout: np.ndarray,
    y_layout: np.ndarray,
    target_index: int,
    rotor_diameter: float,
    hub_height: float,
    model_name: str,
    turbine_number: int,
    y_extent_D: float = 1.5,
    z_min_D: float = 0.1,
    z_max_D: float = 2.05,
    n_y: int = 220,
    n_z: int = 180,
) -> None:
    """
    Plot a report-style PyWake Y-Z plane around the selected turbine.

    This is for visual checking only. The .bts file is still reconstructed using
    the rotor-specific TurbSim grid sampled separately inside write_pywake_superposed_bts().
    """

    D = rotor_diameter
    R = D / 2.0

    # Match the original report convention: positive y/D plotted to the left.
    y_rel_D = np.linspace(-y_extent_D, y_extent_D, n_y)
    z_D = np.linspace(z_min_D, z_max_D, n_z)

    y_rel_m = y_rel_D * D
    z_abs = z_D * D
    y_abs = y_centre + y_rel_m

    U_field, TI_field = extract_pywake_yz_fields(
        sim_res=sim_res,
        x_probe=x_probe,
        y_abs=y_abs,
        z_abs=z_abs,
    )

    Y, Z = np.meshgrid(y_rel_D, z_D, indexing="ij")

    u_vmin = np.floor(np.nanmin(U_field) * 10.0) / 10.0
    u_vmax = np.ceil(np.nanmax(U_field) * 10.0) / 10.0
    u_levels = np.linspace(u_vmin, u_vmax, 40)

    fig, ax = plt.subplots(figsize=(7, 5), constrained_layout=True)

    c0 = ax.contourf(
        Y,
        Z,
        U_field,
        levels=u_levels,
        vmin=u_vmin,
        vmax=u_vmax,
        cmap="viridis",
    )

    ax.axvline(0.0, color="white", linestyle="--", lw=0.7, alpha=0.8)
    ax.axhline(hub_height / D, color="white", linestyle="--", lw=0.7, alpha=0.8)

    # Selected turbine rotor.
    selected_rotor = plt.Circle(
        (0.0, hub_height / D),
        R / D,
        fill=False,
        edgecolor="white",
        linewidth=1.8,
        zorder=5,
    )
    ax.add_patch(selected_rotor)

    # Project nearest upstream rotors into the same Y-Z plane.
    upstream_indices = find_upstream_turbines_for_yz_plane(
        x=x_layout,
        y=y_layout,
        target_index=target_index,
        rotor_diameter=D,
        y_extent_D=y_extent_D,
        max_turbines=2,
    )

    for idx in upstream_indices:
        yD_rel = (y_layout[idx] - y_centre) / D
        upstream_rotor = plt.Circle(
            (yD_rel, hub_height / D),
            R / D,
            fill=False,
            edgecolor="white",
            linestyle="--",
            linewidth=1.1,
            alpha=0.9,
            zorder=4,
        )
        ax.add_patch(upstream_rotor)
        ax.text(
            yD_rel,
            hub_height / D + R / D + 0.05,
            f"T{idx + 1}",
            color="white",
            fontsize=11,
            ha="center",
            va="bottom",
            zorder=6,
        )

    ax.set_xlabel(r"$y/D$")
    ax.set_ylabel(r"$z/D$")
    ax.set_title(rf"T{turbine_number}: {model_name} mean velocity, $x/D=-1$")
    ax.set_aspect("equal", adjustable="box")
    ax.grid(False)
    ax.invert_xaxis()

    cbar = fig.colorbar(c0, ax=ax, shrink=0.92, pad=0.025)
    cbar.set_label(r"$\overline{U}$ [m s$^{-1}$]")

    plt.show()

    rotor_mask = ((Y * D) ** 2 + (Z * D - hub_height) ** 2) <= R**2
    print(f"Full PyWake plane U min/max:  {np.nanmin(U_field):.3f}, {np.nanmax(U_field):.3f}")
    print(f"Rotor-region U mean:          {np.nanmean(U_field[rotor_mask]):.3f}")


