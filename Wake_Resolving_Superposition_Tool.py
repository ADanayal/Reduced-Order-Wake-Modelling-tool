# TURBSIM SUPERPOSITION
# =============================================================================

def superimpose_target_fields_on_turbsim(
    ts: TurbSimFile,
    U_target: np.ndarray,
    TI_target: np.ndarray,
    avoid_reducing_ti: bool = True,
    eps: float = 1e-6,
) -> TurbSimFile:
    """
    Replace the TurbSim mean velocity field and scale streamwise turbulence.

    The baseline TurbSim field is decomposed as:

        U(t, y, z) = Ubar(y, z) + u'(t, y, z)

    The mean field Ubar is replaced by the PyWake target velocity field, and
    the fluctuations are scaled so that the local standard deviation matches
    the target turbulence intensity.
    """

    velocity = ts["u"]
    u_streamwise = velocity[0]  # shape: (nt, ny, nz)

    expected_shape = u_streamwise.shape[1:]
    if U_target.shape != expected_shape:
        raise ValueError(
            f"Target field shape {U_target.shape} does not match TurbSim grid "
            f"shape {expected_shape}."
        )

    Ubar_original = np.mean(u_streamwise, axis=0)
    fluctuations = u_streamwise - Ubar_original[None, :, :]

    sigma_original = np.std(u_streamwise, axis=0)
    TI_original = sigma_original / np.maximum(Ubar_original, eps)

    if avoid_reducing_ti:
        TI_used = np.maximum(TI_target, TI_original)
    else:
        TI_used = TI_target

    sigma_target = TI_used * U_target
    scale = sigma_target / np.maximum(sigma_original, eps)

    u_rebuilt = U_target[None, :, :] + fluctuations * scale[None, :, :]

    if not np.isfinite(u_rebuilt).all():
        raise ValueError("Non-finite values detected in reconstructed velocity field.")

    velocity[0, :, :, :] = u_rebuilt
    ts["u"] = velocity

    return ts


def write_pywake_superposed_bts(
    config: WorkflowConfig,
    sim_res,
    model_name: str,
    x_probe: float,
    y_centre: float,
) -> None:
    """Apply PyWake target fields to each baseline TurbSim file."""

    out_dir = config.output_root / f"T{config.turbine_number}" / "TurbSim" / model_name
    out_dir.mkdir(parents=True, exist_ok=True)

    for seed in config.seeds:
        ts_file = config.baseline_bts_dir / config.baseline_bts_pattern.format(seed=seed)

        if not ts_file.exists():
            raise FileNotFoundError(f"Baseline TurbSim file not found: {ts_file}")

        print(f"Processing model={model_name}, seed={seed}")
        ts = TurbSimFile(str(ts_file))

        y_ts = np.asarray(ts["y"])
        z_ts = np.asarray(ts["z"])

        # TurbSim y-coordinates are relative to the sampled turbine centreline.
        y_abs = y_centre + y_ts

        U_target, TI_target = extract_pywake_yz_fields(
            sim_res=sim_res,
            x_probe=x_probe,
            y_abs=y_abs,
            z_abs=z_ts,
        )
        
        if config.plot_sampled_field and seed == config.seeds[0]:
            plot_pywake_sampled_plane(
                sim_res=sim_res,
                x_probe=x_probe,
                y_centre=y_centre,
                y_ts=y_ts,
                z_ts=z_ts,
                hub_height=config.hub_height,
                rotor_diameter=config.rotor_diameter,
                title=f"{model_name}: rotor-specific PyWake sample, seed {seed}",
            )

        ts = superimpose_target_fields_on_turbsim(
            ts=ts,
            U_target=U_target,
            TI_target=TI_target,
            avoid_reducing_ti=config.avoid_reducing_ti,
        )

        out_file = out_dir / f"15MW_U10_S{seed}_{model_name}_waked.bts"
        ts.write(str(out_file))
        print(f"Saved: {out_file}")


