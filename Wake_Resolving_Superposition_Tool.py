"""
Generalised workflow for constructing wake-resolved TurbSim inflow files
for OpenFAST using PyWake or LES-informed target fields.

This script was developed for the AERO43520 Advanced Research Project:
"Predicting Fatigue Loads of Offshore Wind Turbines Operating in Upstream Wakes".

This script takes baseline TurbSim .bts files generated by the user, samples a
wake field from PyWake at the selected turbine inflow plane, and writes new
wake-resolved .bts files for OpenFAST.

Workflow
--------
1. Generate baseline TurbSim .bts files separately.
2. Define the wind farm layout.
3. Use the original custom_functions.py file to create the turbine, site and
   PyWake wake model.
4. Sample PyWake mean velocity and turbulence intensity on the TurbSim grid.
5. Decompose the baseline TurbSim field into mean and fluctuating components.
6. Replace the mean field with the PyWake wake field.
7. Scale the fluctuations to match the PyWake turbulence intensity field.
8. Save the reconstructed waked .bts file.


Notes
-----
- The script assumes that the baseline TurbSim files already contain realistic
  stochastic turbulence, shear and time variation.
- Wake reconstruction is performed by decomposing the streamwise TurbSim field
  into a mean component and fluctuating component:

      U(t, y, z) = U_mean(y, z) + u'(t, y, z)

  The mean velocity is replaced/scaled using a target wake field, while the
  fluctuations are scaled to match a target turbulence intensity field.
- The default turbine data correspond to the IEA 15 MW reference turbine.
- The default turbine data is also preset to the input conditions considered in 
  accompanying technical report, which the USER needs to change for their own
  conditions.

- The PyWake simulation is set up in accordance to the documentation:
   requiring a turbine, farm and site definition.

Required packages
-----------------
numpy, pandas, matplotlib, scipy, pathlib
py_wake
pyFAST or openfast_toolbox for reading/writing TurbSim .bts files
TurbSim and OpenFAST tool kit envinronments, in order to use the resolved files 


A custom functions file created by PDRA Diego Aray is also provided, 
which is needed in order to correctly implement the various engineering 
wake models correctly.

Edit the file paths in the USER INPUTS section before running.
Author
------
Ahmed Danayal
University of Manchester

Special thanks to Diego Araya
"""
